def stroke_of(char: str) -> tuple[int, bool]:
    """查询单字康熙笔画

    :param char: 单个汉字
    :return: (笔画数, 是否精确值); 未收录时回退简体字数并标记为估计值
    """
    strokes = SURNAME_STROKES.get(char) or NAME_STROKES.get(char)
    if strokes:
        return strokes, True
    return len(char), False
