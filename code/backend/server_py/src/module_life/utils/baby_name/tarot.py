def life_number(birth_date: str) -> int:
    """生命灵数: 出生日期逐位求和迭代至 ≤22

    :param birth_date: 公历出生日期(YYYY-MM-DD)
    :return: 1-22 的生命牌编号
    """
    d = dt.date.fromisoformat(birth_date)
    total = sum(int(ch) for ch in d.isoformat().replace("-", ""))
    while total > 22:
        total = sum(int(ch) for ch in str(total))
    return max(total, 1)


def get_tarot(birth_date: str) -> dict:
    """生命塔罗牌信息

    :return: dict(number, card, meaning, summary)
    """
    num = life_number(birth_date)
    card, meaning = TAROT_CARDS[num]
    return {
        "number": num,
        "card": card,
        "meaning": meaning,
        "summary": f"生命塔罗牌: {card}(编号{num if num < 22 else 0})。寓意: {meaning}",
    }
