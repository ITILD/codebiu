#[cfg(test)]
mod tests {
    use super::*;
    use chrono::Timelike;

    #[test]
    fn solar_term_lichun_2024_matches_reference() {
        // 2024 年立春: 本算法(截断级数近似, 精度优于1分钟)输出 16:27:06,
        // 与 Python 参考实现一致(高精度天文公认值为 16:26:53, 偏差属算法设计精度)
        let t = solar_term_time(2024, 315.0);
        assert_eq!(t.date(), NaiveDate::from_ymd_opt(2024, 2, 4).unwrap());
        assert_eq!(t.hour(), 16);
        assert_eq!(t.minute(), 27);
        assert_eq!(t.second(), 6);
    }

    #[test]
    fn solar_term_xiaohan_boundary_year() {
        // 2024 年小寒: 2024-01-06 04:49(北京时间)
        let t = solar_term_time(2024, 285.0);
        assert_eq!(t.date(), NaiveDate::from_ymd_opt(2024, 1, 6).unwrap());
        assert_eq!(t.hour(), 4);
        assert_eq!(t.minute(), 49);
    }

    #[test]
    fn solar_term_daxue_2023() {
        // 2023 年大雪: 2023-12-07 17:32(北京时间)
        let t = solar_term_time(2023, 255.0);
        assert_eq!(t.date(), NaiveDate::from_ymd_opt(2023, 12, 7).unwrap());
        assert_eq!(t.hour(), 17);
        assert_eq!(t.minute(), 32);
    }
}
