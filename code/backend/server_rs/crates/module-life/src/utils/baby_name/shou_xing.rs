/// 经度章动(弧度), t 为 J2000 起儒略世纪数
fn nutation_lon(t: f64) -> f64 {
    let t2 = t * t;
    let mut dl = 0.0;
    let mut i = 0usize;
    while i < NUT_B.len() {
        let a = if i == 0 { -1.742 * t } else { 0.0 };
        dl += (NUT_B[i + 3] + a) * (NUT_B[i] + NUT_B[i + 1] * t + NUT_B[i + 2] * t2).sin();
        i += 5;
    }
    dl / 100.0 / SECOND_PER_RAD
}

/// 地球日心黄经(弧度): t 为 J2000 起儒略世纪数, n 取级数项比例(-1=全项)
fn e_lon(t: f64, n: i32) -> f64 {
    let t = t / 10.0;
    let mut v = 0.0;
    let mut tn = 1.0;
    let pn = 1usize;
    let m0 = XL0[pn + 1] - XL0[pn];
    for i in 0..6usize {
        let n1 = XL0[pn + i] as usize;
        let n2 = XL0[pn + 1 + i] as usize;
        let n0 = n2 - n1;
        if n0 == 0 {
            continue;
        }
        let m = if n < 0 {
            n2
        } else {
            let mut m = (3.0 * n as f64 * n0 as f64 / m0 + 0.5) as usize + n1;
            if i != 0 {
                m += 3;
            }
            if m > n2 {
                m = n2;
            }
            m
        };
        let mut c = 0.0;
        let mut j = n1;
        while j < m {
            c += XL0[j] * (XL0[j + 1] + t * XL0[j + 2]).cos();
            j += 3;
        }
        v += c * tn;
        tn *= t;
    }
    v /= XL0[0];
    let t2 = t * t;
    let t3 = t2 * t;
    v + (-0.0728 - 2.7702 * t - 1.1019 * t2 - 0.0996 * t3) / SECOND_PER_RAD
}

/// 太阳光行差修正(弧度), t 为 J2000 起儒略世纪数
fn gxc_sun_lon(t: f64) -> f64 {
    let v = -0.043126 + 628.301955 * t - 0.000002732 * t * t;
    let e = 0.016708634 - 0.000042037 * t - 0.0000001267 * t * t;
    -20.49552 * (1.0 + e * v.cos()) / SECOND_PER_RAD
}

/// 太阳黄经变率(弧度/世纪), 供牛顿迭代加速
fn ev(t: f64) -> f64 {
    let f = 628.307585 * t;
    628.332 + 21.0 * (1.527 + f).sin() + 0.44 * (1.48 + f * 2.0).sin()
        + 0.129 * (5.82 + f).sin() * t
        + 0.00055 * (4.21 + f).sin() * t * t
}

/// 太阳视黄经(弧度): 地球黄经 + 章动 + 光行差 + 180°
fn sa_lon(t: f64, n: i32) -> f64 {
    e_lon(t, n) + nutation_lon(t) + gxc_sun_lon(t) + PI
}

/// ΔT 远年外推
fn dt_ext(y: f64, jsd: f64) -> f64 {
    let dy = (y - 1820.0) / 100.0;
    -20.0 + jsd * dy * dy
}

/// ΔT(秒) 分段拟合
fn dt_calc(y: f64) -> f64 {
    let size = DT_AT.len();
    let y0 = DT_AT[size - 2];
    let t0 = DT_AT[size - 1];
    if y >= y0 {
        let jsd = 31.0;
        if y > y0 + 100.0 {
            return dt_ext(y, jsd);
        }
        let v = dt_ext(y, jsd);
        let dv = dt_ext(y0, jsd) - t0;
        return v - dv * (y0 + 100.0 - y) / 100.0;
    }
    let mut i = 0usize;
    let mut idx = 0usize;
    while i < size {
        idx = i;
        if y < DT_AT[i + 5] {
            break;
        }
        i += 5;
    }
    let t1 = (y - DT_AT[idx]) / (DT_AT[idx + 5] - DT_AT[idx]) * 10.0;
    let t2 = t1 * t1;
    let t3 = t2 * t1;
    DT_AT[idx + 1] + DT_AT[idx + 2] * t1 + DT_AT[idx + 3] * t2 + DT_AT[idx + 4] * t3
}

/// ΔT(日), t 为 J2000 起儒略日数
fn dt_t(t: f64) -> f64 {
    dt_calc(t / 365.2425 + 2000.0) / 86400.0
}

/// 牛顿迭代: 太阳视黄经到达 w(弧度)的瞬间, 返回 J2000 起儒略世纪数(TT)
fn sa_lon_t(w: f64) -> f64 {
    let mut v = 628.3319653318;
    let mut t = (w - 1.75347 - PI) / v;
    v = ev(t);
    t += (w - sa_lon(t, 10)) / v;
    v = ev(t);
    t += (w - sa_lon(t, -1)) / v;
    t
}

/// 太阳视黄经到达 w 的节气时刻(北京时间), 返回 J2000 起儒略日数
fn qi_accurate(w: f64) -> f64 {
    let t = sa_lon_t(w) * 36525.0;
    t - dt_t(t) + ONE_THIRD
}

/// 公历 year 年内视黄经 deg 度的节气时刻(北京时间, 精度优于1分钟)
///
/// 牛顿迭代的初值分支决定收敛到哪个 2π 周期(J2000 历元太阳黄经约 280°,
/// 黄经低于它的节气初值会偏早一年), 这里按结果年份自动增减整周期,
/// 保证落在公历 year 年内。
pub fn solar_term_time(year: i32, deg: f64) -> NaiveDateTime {
    let w0 = deg * PI / 180.0 + TWO_PI * (year - 2000) as f64;
    let mut jd = qi_accurate(w0);
    let base = NaiveDate::from_ymd_opt(2000, 1, 1)
        .and_then(|d| d.and_hms_opt(12, 0, 0))
        .expect("基准时刻合法");
    let mut result = base + Duration::milliseconds((jd * 86400.0 * 1000.0) as i64);
    // 初值分支可能落在相邻年份: 视黄经低于 J2000 历元黄经的节气会偏早一年
    let mut k = 0i32;
    if result.year() < year {
        k = 1;
    } else if result.year() > year {
        k = -1;
    }
    if k != 0 {
        jd = qi_accurate(w0 + TWO_PI * k as f64);
        result = base + Duration::milliseconds((jd * 86400.0 * 1000.0) as i64);
    }
    result
}

